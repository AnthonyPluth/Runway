"""tools/pr_screenshots.py: the comment markdown, which files it takes, its arguments, and the git part against a
throwaway repository (no network)."""
import importlib.util
import io
import subprocess
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("pr_screenshots", ROOT / "tools" / "pr_screenshots.py")
assert _spec and _spec.loader
ps = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ps)

TRAILERS = ["Claude-Session: https://example.test/s"]
SHA = "0123456789abcdef0123456789abcdef01234567"


def run(cwd, *args):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout


class Markdown(unittest.TestCase):
    NAMES = ["budget-desktop-top.png", "budget-phone-top.png", "budget-tablet-top.png", "setup-phone-top.png"]

    def test_headings_per_width_in_order_with_raw_urls_and_the_footer(self):
        md = ps.comment_markdown(42, self.NAMES, SHA)
        self.assertLess(md.index("**Phone (390 px)**"), md.index("**Tablet (768 px)**"))
        self.assertLess(md.index("**Tablet (768 px)**"), md.index("**Desktop (1280 px)**"))
        self.assertIn(f"![Budget at phone width](https://raw.githubusercontent.com/AnthonyPluth/Runway/{SHA}/screenshots/pr-42/budget-phone-top.png)", md)
        self.assertIn("![Setup at phone width]", md)
        self.assertTrue(md.startswith("## Screenshots (`make verify`, made-up demo data, dark theme)"))
        self.assertNotIn("Not checked", md)
        self.assertTrue(md.endswith("---\n_Generated by [Claude Code](https://claude.ai/code)_\n"))

    def test_the_heading_names_the_theme_shown(self):
        md = ps.comment_markdown(1, ["a-phone-top.png"], SHA, theme="light")
        self.assertIn("light theme)", md)
        self.assertNotIn("Not checked", md)

    def test_a_file_without_a_width_goes_under_other(self):
        md = ps.comment_markdown(1, ["flow-x-open.png"], SHA)
        self.assertIn("**Other**", md)
        self.assertNotIn("**Phone", md)

    def test_alt_text_names_page_and_width(self):
        self.assertEqual(ps.alt_text("flow-emoji-open-desktop-top.png"), "Flow emoji open at desktop width")
        self.assertEqual(ps.alt_text("odd.png"), "Odd")


class Selection(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.dir = Path(tmp.name)
        for n in ("a-phone.png", "a-phone-top.png", "b-tablet-top.png", "notes.txt"):
            (self.dir / n).write_bytes(b"x")

    def test_default_is_every_top_screenshot_not_the_full_page_ones(self):
        self.assertEqual([p.name for p in ps.select_files([], self.dir)], ["a-phone-top.png", "b-tablet-top.png"])

    def test_named_files_are_used_as_given(self):
        self.assertEqual(ps.select_files([str(self.dir / "a-phone.png")], self.dir), [self.dir / "a-phone.png"])

    def test_refuses_nothing_missing_and_non_png_files(self):
        with self.assertRaisesRegex(ps.ScreenshotError, "no \\*-top.png"):
            ps.select_files([], self.dir / "empty")
        with self.assertRaisesRegex(ps.ScreenshotError, "doesn't exist"):
            ps.select_files([str(self.dir / "gone.png")], self.dir)
        with self.assertRaisesRegex(ps.ScreenshotError, "isn't a .png"):
            ps.select_files([str(self.dir / "notes.txt")], self.dir)

    def test_only_screenshots_in_the_verify_folder_are_published(self):
        elsewhere = self.dir / "elsewhere"
        elsewhere.mkdir()
        (elsewhere / "real-instance.png").write_bytes(b"x")
        with self.assertRaisesRegex(ps.ScreenshotError, "only `make verify`'s screenshots"):
            ps.select_files([str(elsewhere / "real-instance.png")], self.dir)
        link = self.dir / "looks-fine-top.png"
        link.symlink_to(elsewhere / "real-instance.png")
        with self.assertRaisesRegex(ps.ScreenshotError, "only `make verify`'s screenshots"):
            ps.select_files([str(link)], self.dir)
        with self.assertRaisesRegex(ps.ScreenshotError, "only `make verify`'s screenshots"):
            ps.select_files([str(self.dir / "elsewhere" / ".." / ".." / "x-top.png")], self.dir)


class Arguments(unittest.TestCase):
    def test_parses_pr_files_and_theme(self):
        a = ps.parse_args(["7", "x.png", "--theme", "light", "--trailer", "A: b"])
        self.assertEqual((a.pr, a.files, a.theme, a.trailer), (7, ["x.png"], "light", ["A: b"]))

    def test_rejects_a_bad_pr_number(self):
        for bad in (["0"], ["abc"], []):
            with redirect_stderr(io.StringIO()), self.assertRaises(SystemExit):
                ps.parse_args(bad)

    def test_trailers_come_from_the_environment_then_flags(self):
        self.assertEqual(ps.trailers_from({"PR_SCREENSHOTS_TRAILERS": "A: 1\n\nB: 2\n"}, ["C: 3"]), ["A: 1", "B: 2", "C: 3"])
        self.assertEqual(ps.trailers_from({}, []), [])

    def test_commit_message_ends_with_the_trailers_and_needs_no_model(self):
        self.assertTrue(ps.commit_message(5, TRAILERS).endswith("\n".join(TRAILERS) + "\n"))
        self.assertEqual(ps.commit_message(5, []), "Update screenshots for PR #5\n\nMade-up demo data from `make verify`.\n")

    def test_the_url_pins_a_commit_not_a_branch(self):
        self.assertEqual(ps.raw_url(7, "a-phone-top.png", SHA),
                         f"https://raw.githubusercontent.com/AnthonyPluth/Runway/{SHA}/screenshots/pr-7/a-phone-top.png")

    def test_refuses_to_run_outside_the_repository(self):
        with tempfile.TemporaryDirectory() as elsewhere, redirect_stderr(io.StringIO()) as err, redirect_stdout(io.StringIO()):
            self.assertEqual(ps.main(["1", "x.png"], cwd=Path(elsewhere)), 2)
        self.assertIn("inside the Runway repository", err.getvalue())


class Committing(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        base = Path(tmp.name)
        self.remote = base / "remote.git"
        run(base, "init", "--bare", "-b", "main", str(self.remote))
        self.repo = base / "repo"
        run(base, "clone", "-q", str(self.remote), str(self.repo))
        for k, v in (("user.name", "Test"), ("user.email", "test@example.test")):
            run(self.repo, "config", k, v)
        (self.repo / "app.txt").write_text("app\n")
        run(self.repo, "add", ".")
        run(self.repo, "commit", "-q", "-m", "init")
        run(self.repo, "push", "-q", "origin", "HEAD:main")
        run(self.repo, "checkout", "-q", "-b", "feature")
        self.shots = base / "shots"
        self.shots.mkdir()

    def shot(self, name, data=b"png"):
        p = self.shots / name
        p.write_bytes(data)
        return p

    def commit(self, pr, files, trailers=TRAILERS):
        return ps.commit_screenshots(self.repo, pr, files, trailers)

    def head_files(self):
        return run(self.repo, "ls-tree", "-r", "--name-only", "HEAD").split()

    def test_copies_the_files_into_the_folder_and_commits_on_the_current_branch(self):
        sha = self.commit(311, [self.shot("t-phone-top.png"), self.shot("t-tablet-top.png")])
        self.assertEqual(sha, run(self.repo, "rev-parse", "HEAD").strip())
        self.assertEqual(run(self.repo, "branch", "--show-current").strip(), "feature")
        self.assertEqual(self.head_files(), ["app.txt", "screenshots/pr-311/t-phone-top.png", "screenshots/pr-311/t-tablet-top.png"])
        self.assertEqual((self.repo / "screenshots" / "pr-311" / "t-phone-top.png").read_bytes(), b"png")
        self.assertTrue(run(self.repo, "log", "-1", "--format=%B").strip().endswith(TRAILERS[-1]))
        self.assertEqual(run(self.repo, "status", "--porcelain"), "")

    def test_nothing_is_pushed_and_no_other_branch_is_made(self):
        self.commit(5, [self.shot("a-phone-top.png")])
        self.assertEqual(run(self.remote, "branch", "--format=%(refname:short)").split(), ["main"])
        self.assertEqual(run(self.repo, "branch", "--format=%(refname:short)").split(), ["feature", "main"])

    def test_the_sha_in_the_link_is_a_commit_that_holds_the_files(self):
        sha = self.commit(5, [self.shot("a-phone-top.png", b"one")])
        url = ps.raw_url(5, "a-phone-top.png", sha)
        self.assertIn(f"/{sha}/screenshots/pr-5/a-phone-top.png", url)
        self.assertEqual(run(self.repo, "show", f"{sha}:screenshots/pr-5/a-phone-top.png"), "one")

    def test_rerunning_replaces_that_prs_folder_and_keeps_other_prs(self):
        self.commit(1, [self.shot("a-phone-top.png", b"one")])
        self.commit(2, [self.shot("a-phone-top.png", b"two")])
        self.commit(1, [self.shot("b-phone-top.png", b"three")])
        self.assertEqual(self.head_files(), ["app.txt", "screenshots/pr-1/b-phone-top.png", "screenshots/pr-2/a-phone-top.png"])
        self.assertEqual(run(self.repo, "show", "HEAD:screenshots/pr-2/a-phone-top.png"), "two")

    def test_unchanged_files_make_no_new_commit(self):
        files = [self.shot("a-phone-top.png")]
        first = self.commit(9, files)
        self.assertEqual(self.commit(9, files), first)
        self.assertEqual(run(self.repo, "rev-list", "--count", "main..HEAD").strip(), "1")

    def test_only_the_screenshots_are_committed(self):
        (self.repo / "staged.txt").write_text("x")
        run(self.repo, "add", "staged.txt")
        self.commit(4, [self.shot("a-phone-top.png")])
        self.assertNotIn("staged.txt", self.head_files())
        self.assertEqual(run(self.repo, "status", "--porcelain").strip(), "A  staged.txt")


if __name__ == "__main__":
    unittest.main()
