"""Shows a UI pull request's `make verify` screenshots inline. Standard library only.

Screenshots in artifacts/verify/ are gitignored and the GitHub API can't attach an image to a comment, so they are copied
into `screenshots/pr-<n>/` in the working tree and committed on the PR's own branch. The comment embeds them through
raw.githubusercontent.com, pinned to the commit that holds them, so the links survive the branch being deleted. This
script does that and prints the markdown to post as the comment.

    python tools/pr_screenshots.py <pr number> [file.png …] [--theme dark] [--trailer "Key: value"]

With no files it takes every `*-top.png` in artifacts/verify/ (the viewport-only screenshots `make verify` saves beside
the full-page ones, which are thousands of pixels tall). Only ever publish `make verify`'s made-up demo data: the
repository is public.

Running it again for the same pull request replaces that folder's files, and commits only when they changed. The commit
holds only `screenshots/pr-<n>/` (anything else you have staged stays staged) and ends with the trailers in
$PR_SCREENSHOTS_TRAILERS (one per line) and any --trailer. It never pushes: push the branch before posting the comment, and
run it again after a rebase or amend rewrites the commit, since the links name a commit."""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERIFY_DIR = ROOT / "artifacts" / "verify"
SHOTS_DIR = "screenshots"
REPO_SLUG = "AnthonyPluth/Runway"
WIDTHS = {"phone": 390, "tablet": 768, "desktop": 1280}
THEMES = ("dark", "light")
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"


class ScreenshotError(Exception):
    """Something the person running this can fix; main prints it without a traceback."""


def raw_url(pr: int, name: str, sha: str, slug: str = REPO_SLUG) -> str:
    """Pinned to a commit, not a branch, so the link keeps working after the branch is deleted."""
    return f"https://raw.githubusercontent.com/{slug}/{sha}/{SHOTS_DIR}/pr-{pr}/{name}"


def viewport_of(name: str) -> str | None:
    m = re.search(r"-(phone|tablet|desktop)(?:-top)?\.png$", name)
    return m.group(1) if m else None


def alt_text(name: str) -> str:
    """'transactions-phone-top.png' -> 'Transactions at phone width'."""
    viewport = viewport_of(name)
    page = re.sub(r"-(?:phone|tablet|desktop)(?:-top)?\.png$|-top\.png$|\.png$", "", name).replace("-", " ").replace("_", " ")
    page = page[:1].upper() + page[1:]
    return f"{page} at {viewport} width" if viewport else page


def select_files(paths: Sequence[str], verify_dir: Path = VERIFY_DIR) -> list[Path]:
    """The files to publish: the ones named, else every *-top.png in verify_dir. Each must be in verify_dir (so a screenshot
    of a real instance can't be published by naming it), exist, be a PNG."""
    chosen = [Path(p) for p in paths] if paths else sorted(verify_dir.glob("*-top.png"))
    for p in chosen:
        if p.resolve().parent != verify_dir.resolve():
            raise ScreenshotError(f"{p} isn't in {verify_dir}: only `make verify`'s screenshots, taken on made-up demo data, are published "
                                  "(the branch is public)")
    if not chosen:
        raise ScreenshotError(f"no *-top.png screenshots in {verify_dir}: run `make verify` first (or name the files)")
    for p in chosen:
        if p.suffix.lower() != ".png":
            raise ScreenshotError(f"{p} isn't a .png file")
        if not p.is_file():
            raise ScreenshotError(f"{p} doesn't exist")
    return chosen


def comment_markdown(pr: int, names: Sequence[str], sha: str, theme: str = "dark", slug: str = REPO_SLUG) -> str:
    """The PR comment: a heading per width (phone, tablet, desktop; any other file under 'Other'), each image embedded
    from the commit, a line on what it is, and the attribution footer."""
    groups: dict[str, list[str]] = {}
    for name in sorted(names):
        groups.setdefault(viewport_of(name) or "other", []).append(name)
    out = [f"## Screenshots (`make verify`, made-up demo data, {theme} theme)", ""]
    for key in (*WIDTHS, "other"):
        if key not in groups:
            continue
        out += [f"**{key.capitalize()} ({WIDTHS[key]} px)**" if key in WIDTHS else "**Other**", ""]
        out += [f"![{alt_text(n)}]({raw_url(pr, n, sha, slug)})\n" for n in groups[key]]
    out.append(FOOTER)
    return "\n".join(out) + "\n"


def trailers_from(env: dict[str, str], extra: Sequence[str]) -> list[str]:
    lines = [t.strip() for t in env.get("PR_SCREENSHOTS_TRAILERS", "").splitlines() if t.strip()]
    lines += [t.strip() for t in extra if t.strip()]
    return lines


def commit_message(pr: int, trailers: Sequence[str]) -> str:
    message = f"Update screenshots for PR #{pr}\n\nMade-up demo data from `make verify`.\n"
    return message + ("\n" + "\n".join(trailers) + "\n" if trailers else "")


def parse_args(argv: Sequence[str]) -> argparse.Namespace:
    ap = argparse.ArgumentParser(prog="pr_screenshots.py", description="Commit make verify screenshots for a PR and print its comment.")
    ap.add_argument("pr", type=int, help="the pull request's number")
    ap.add_argument("files", nargs="*", help="screenshots to commit (default: every *-top.png in artifacts/verify/)")
    ap.add_argument("--theme", choices=sorted(THEMES), default="dark", help="the theme the screenshots show (default dark)")
    ap.add_argument("--trailer", action="append", default=[], help="a commit trailer, 'Key: value' (repeatable)")
    args = ap.parse_args(argv)
    if args.pr < 1:
        ap.error("the pull request number must be positive")
    return args


def git(cwd: Path, *args: str, ok: Sequence[int] = (0,)) -> subprocess.CompletedProcess[str]:
    done = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if done.returncode not in ok:
        raise ScreenshotError(f"git {' '.join(args)} failed ({done.returncode}): {(done.stderr or done.stdout).strip()}")
    return done


def inside(path: Path, root: Path = ROOT) -> bool:
    return path.resolve() == root or root in path.resolve().parents


def commit_screenshots(repo: Path, pr: int, files: Sequence[Path], trailers: Sequence[str] = ()) -> str:
    """Replaces screenshots/pr-<pr>/ in the working tree with files and commits it on the current branch, touching nothing
    else. Returns the sha of HEAD, which holds the folder as it now is; nothing is committed when it already matched."""
    folder = repo / SHOTS_DIR / f"pr-{pr}"
    rel = f"{SHOTS_DIR}/pr-{pr}"
    shutil.rmtree(folder, ignore_errors=True)   # re-running replaces the folder; there may be none yet
    folder.mkdir(parents=True)
    for f in files:
        shutil.copyfile(f, folder / f.name)
    git(repo, "add", "-A", "--", rel)
    if git(repo, "status", "--porcelain", "--", rel).stdout.strip():
        git(repo, "commit", "--quiet", "-m", commit_message(pr, trailers), "--", rel)
    return git(repo, "rev-parse", "HEAD").stdout.strip()


def main(argv: Sequence[str], cwd: Path | None = None, env: dict[str, str] | None = None) -> int:
    args = parse_args(argv)
    here = (cwd or Path.cwd()).resolve()
    if not inside(here):
        print(f"pr_screenshots: run this inside the Runway repository ({ROOT}), not {here}", file=sys.stderr)
        return 2
    try:
        files = select_files(args.files)
        before = git(ROOT, "rev-parse", "HEAD").stdout.strip()
        sha = commit_screenshots(ROOT, args.pr, files, trailers_from(env if env is not None else dict(os.environ), args.trailer))
    except ScreenshotError as e:
        print(f"pr_screenshots: {e}", file=sys.stderr)
        return 1
    print(f"pr_screenshots: {'committed' if sha != before else 'already up to date:'} {len(files)} file(s) in {SHOTS_DIR}/pr-{args.pr}/ "
          f"({sha[:9]}); push the branch before posting the comment", file=sys.stderr)
    print(comment_markdown(args.pr, [f.name for f in files], sha, args.theme))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
